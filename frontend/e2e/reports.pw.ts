import { expect, test } from '@playwright/test'

const email = process.env.CPDTS_E2E_B, both = process.env.CPDTS_E2E_A, password = process.env.CPDTS_E2E_PASSWORD, nonce = process.env.CPDTS_E2E_NONCE
if (!email || !both || !password || !nonce) throw new Error('Use the guarded browser test runner.')

test('reports filters, pagination and company isolation on desktop and mobile', async ({ page }) => {
  expect((await page.request.get('/api/v1/auth/csrf')).headers()['x-cpdts-browser-test']).toBe(nonce)
  await page.goto('/login')
  await page.getByLabel('Email address').fill(both!)
  await page.getByLabel('Password').fill(password!)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
  const companies = await page.evaluate(async () => await (await fetch('/api/v1/auth/companies')).json() as { id: number; code: string }[])
  const kam = companies.find(c => c.code === 'KAM')!.id
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByLabel('Email address').fill(email!)
  await page.getByLabel('Password').fill(password!)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.getByRole('link', { name: 'Reports' }).click()
  await expect(page.getByRole('heading', { name: 'Customer debt' })).toBeVisible()
  expect(await page.evaluate(async id => (await fetch(`/api/v1/companies/${id}/reports/debt/customers`)).status, kam)).toBe(403)
  await page.getByLabel('Search', { exact: true }).fill('not-a-customer-xyz-123')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByText('No report results found.')).toBeVisible()
  await page.getByLabel('Search', { exact: true }).fill('')
  const response = page.waitForResponse(r => r.url().includes('/reports/debt/customers?') && r.status() === 200)
  await page.getByRole('button', { name: 'Apply filters' }).click()
  const data = await (await response).json()
  if (Number(data.totalPages) > 1) {
    const next = page.waitForResponse(r => r.url().includes('/reports/debt/customers?') && new URL(r.url()).searchParams.get('page') === '1')
    await page.getByRole('button', { name: 'Next' }).click()
    expect((await next).status()).toBe(200)
    await expect(page.getByText(/Page 2 of/)).toBeVisible()
  }
  await page.locator('label').filter({ hasText: 'Report' }).locator('select').selectOption('invoices')
  await page.getByLabel('Invoice scope').selectOption('true')
  const invoices = page.waitForResponse(r => r.url().includes('/reports/debt/invoices?') && new URL(r.url()).searchParams.get('overdueOnly') === 'true')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  expect((await invoices).status()).toBe(200)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('label').filter({ hasText: 'Report' }).locator('select').selectOption('payments')
  await page.getByLabel('Method').selectOption('CASH')
  await page.getByLabel('Received from (Tanzania)').fill('2026-01-01')
  await page.getByLabel('Received to (Tanzania)').fill('2026-12-31')
  const payments = page.waitForResponse(r => r.url().includes('/reports/payments?') && new URL(r.url()).searchParams.get('method') === 'CASH')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  expect((await payments).status()).toBe(200)
  await expect(page.getByText(/statuses are current, not historical/i)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
